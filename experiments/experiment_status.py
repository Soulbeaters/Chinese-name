# -*- coding: utf-8 -*-
"""
实验状态检查工具 / Experiment Status Checker

动态检查实验运行状态，避免硬编码"301k已完成"等状态
Dynamically check experiment run status, avoid hardcoding completion status

作者: Ma Jiaxin
日期: 2025-12-20
"""

import sys
import subprocess
from pathlib import Path
from typing import Dict, Any, List, Optional
from enum import Enum


class ExperimentStatus(Enum):
    """实验状态枚举 / Experiment Status Enum"""
    NOT_STARTED = "not_started"  # 目录不存在
    RUNNING = "running"          # 目录存在但输出不完整
    COMPLETED = "completed"      # 所有输出完整且通过验证
    FAILED = "failed"            # 验证失败


def check_experiment_status(
    run_dir: str,
    require_validation: bool = True
) -> Dict[str, Any]:
    """
    检查实验运行状态 / Check experiment run status

    Args:
        run_dir: 实验输出目录路径
        require_validation: 是否要求通过validate_deliverables验证

    Returns:
        Dict包含:
        - status: ExperimentStatus枚举值
        - status_str: 状态字符串 ("not_started", "running", "completed", "failed")
        - status_emoji: 状态emoji ("🔄", "✅", "❌", "⏸️")
        - missing_files: 缺失的关键文件列表
        - validation_passed: 是否通过验证 (None if not checked)
        - validation_error: 验证错误信息 (None if passed or not checked)
        - details: 详细信息
    """
    run_path = Path(run_dir)

    # Check 1: 目录是否存在
    if not run_path.exists():
        return {
            "status": ExperimentStatus.NOT_STARTED,
            "status_str": "not_started",
            "status_emoji": "⏸️",
            "missing_files": [],
            "validation_passed": None,
            "validation_error": None,
            "details": f"Directory does not exist: {run_dir}"
        }

    # (P0-P3收敛任务2): 区分benchmark vs evidence-chain run类型
    # Distinguish benchmark vs evidence-chain run types
    # Check if this is a performance benchmark run
    is_benchmark = (run_path / "performance_benchmark.json").exists()

    # Check 2: 关键文件是否存在 (根据实验类型确定)
    # Check required files based on experiment type
    if is_benchmark:
        # Performance benchmark: 只要求benchmark特有文件
        # Only require benchmark-specific files
        required_files = [
            "performance_benchmark.json"
            # env.txt is optional (may not be generated by all benchmark scripts)
        ]
    else:
        # Evidence-chain experiment: 要求完整的统计输出
        # Require full statistical outputs
        required_files = [
            "run_manifest.json",
            "statistics/stats_ci_global.json",
            "statistics/stats_ci_global.md",
            "statistics/stats_ci_global.tex"
        ]

    missing_files = []
    for file_rel_path in required_files:
        file_path = run_path / file_rel_path
        if not file_path.exists():
            missing_files.append(file_rel_path)

    if missing_files:
        run_type_label = "benchmark" if is_benchmark else "evidence-chain"
        return {
            "status": ExperimentStatus.RUNNING,
            "status_str": "running",
            "status_emoji": "🔄",
            "missing_files": missing_files,
            "validation_passed": None,
            "validation_error": None,
            "run_type": run_type_label,
            "details": f"[{run_type_label}] Missing {len(missing_files)} required file(s): {', '.join(missing_files[:3])}"
        }

    # Check 3: 验证交付物 (如果要求)
    # (P0-P3收敛任务2): benchmark run跳过validation (validator是为evidence-chain设计的)
    # Skip validation for benchmark runs (validator is designed for evidence-chain)
    validation_passed = None
    validation_error = None

    if require_validation and not is_benchmark:
        try:
            # Run validate_deliverables.py
            validator_script = Path(__file__).parent / "validate_deliverables.py"

            result = subprocess.run(
                [sys.executable, str(validator_script), str(run_path)],
                capture_output=True,
                text=True,
                timeout=30
            )

            validation_passed = (result.returncode == 0)

            if not validation_passed:
                # (P0-P3收敛任务1): 完整保存stderr和stdout，不截断
                # Save full stderr and stdout, do not truncate
                stderr = result.stderr.strip()
                stdout = result.stdout.strip()

                # 完整的验证错误信息 (优先使用stdout，因为validate_deliverables主要输出到stdout)
                # Full validation error (prefer stdout as validate_deliverables outputs to stdout)
                validation_error = stdout if stdout else stderr

                # 提取最后20行作为summary (用于简短显示)
                # Extract last 20 lines for summary display
                error_lines = validation_error.split('\n')
                last_20_lines = '\n'.join(error_lines[-20:]) if len(error_lines) > 20 else validation_error

        except subprocess.TimeoutExpired:
            validation_passed = False
            validation_error = "Validation script timeout (>30s)"
            last_20_lines = validation_error

        except Exception as e:
            validation_passed = False
            validation_error = f"Validation script error: {str(e)}"
            last_20_lines = validation_error

    # 根据验证结果决定最终状态
    run_type_label = "benchmark" if is_benchmark else "evidence-chain"

    if require_validation and not is_benchmark and not validation_passed:
        return {
            "status": ExperimentStatus.FAILED,
            "status_str": "failed",
            "status_emoji": "❌",
            "missing_files": [],
            "validation_passed": False,
            "validation_error": validation_error,  # 完整错误信息 / Full error info
            "validation_error_summary": last_20_lines,  # 最后20行摘要 / Last 20 lines summary
            "run_type": run_type_label,
            "details": f"[{run_type_label}] Validation failed (see validation_error for full output)"
        }
    else:
        # Completed (either passed validation or is a benchmark without validation)
        validation_note = ""
        if is_benchmark:
            validation_note = " (benchmark: validation skipped)"
        elif require_validation:
            validation_note = " and validation passed"

        return {
            "status": ExperimentStatus.COMPLETED,
            "status_str": "completed",
            "status_emoji": "✅",
            "missing_files": [],
            "validation_passed": validation_passed,
            "validation_error": None,
            "run_type": run_type_label,
            "details": f"[{run_type_label}] All required files present{validation_note}"
        }


def check_multiple_experiments(
    experiment_dirs: Dict[str, str],
    require_validation: bool = True
) -> Dict[str, Dict[str, Any]]:
    """
    批量检查多个实验状态 / Check multiple experiment statuses

    Args:
        experiment_dirs: 实验名称 -> 目录路径的字典
        require_validation: 是否要求验证

    Returns:
        实验名称 -> 状态信息的字典
    """
    results = {}

    for exp_name, exp_dir in experiment_dirs.items():
        results[exp_name] = check_experiment_status(exp_dir, require_validation)

    return results


def generate_status_report(
    experiment_dirs: Dict[str, str],
    require_validation: bool = True
) -> str:
    """
    生成实验状态报告 (Markdown格式)
    Generate experiment status report (Markdown format)

    Args:
        experiment_dirs: 实验名称 -> 目录路径的字典
        require_validation: 是否要求验证

    Returns:
        Markdown格式的状态报告
    """
    statuses = check_multiple_experiments(experiment_dirs, require_validation)

    lines = [
        "# 实验状态报告 / Experiment Status Report",
        "",
        f"**检查时间**: {Path(__file__).stat().st_mtime}",
        f"**验证要求**: {'是 (require validate_deliverables)' if require_validation else '否'}",
        "",
        "---",
        "",
        "## 实验状态总览 / Experiment Status Overview",
        "",
        "| 实验名称 | 状态 | 详情 |",
        "|---------|------|------|"
    ]

    for exp_name, status_info in statuses.items():
        emoji = status_info["status_emoji"]
        status_str = status_info["status_str"]
        details = status_info["details"]

        lines.append(f"| {exp_name} | {emoji} {status_str} | {details} |")

    lines.extend([
        "",
        "---",
        "",
        "## 状态说明 / Status Explanation",
        "",
        "- ⏸️ **not_started**: 实验目录不存在",
        "- 🔄 **running**: 实验目录存在，但关键输出文件缺失",
        "- ✅ **completed**: 所有关键文件存在，且通过验证",
        "- ❌ **failed**: 文件存在但验证失败",
        "",
        "---",
        "",
        "## 详细信息 / Detailed Information",
        ""
    ])

    for exp_name, status_info in statuses.items():
        lines.append(f"### {exp_name}")
        lines.append("")
        lines.append(f"- **状态**: {status_info['status_emoji']} {status_info['status_str']}")
        lines.append(f"- **详情**: {status_info['details']}")

        if status_info["missing_files"]:
            lines.append(f"- **缺失文件** ({len(status_info['missing_files'])}个):")
            for missing_file in status_info["missing_files"]:
                lines.append(f"  - `{missing_file}`")

        if status_info.get("validation_error"):
            # (P0-P3收敛任务1): 输出完整错误，不截断
            # Output full error, do not truncate
            lines.append(f"- **验证错误 (完整输出)**:")
            lines.append(f"  ```")
            # 使用summary版本（最后20行）避免报告过长
            # Use summary version (last 20 lines) to avoid too long report
            error_summary = status_info.get('validation_error_summary', status_info['validation_error'])
            lines.append(f"  {error_summary}")
            lines.append(f"  ```")
            lines.append(f"  *(完整错误信息见status_info['validation_error'])*")

        lines.append("")

    return "\n".join(lines)


def main():
    """命令行入口 / CLI Entry Point"""
    import argparse
    import sys
    import io

    # Fix Windows GBK encoding issue
    if sys.platform == 'win32':
        sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')
        sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding='utf-8', errors='replace')

    parser = argparse.ArgumentParser(
        description="检查实验运行状态 / Check experiment run status"
    )
    parser.add_argument(
        "run_dir",
        help="实验输出目录 / Experiment output directory"
    )
    parser.add_argument(
        "--no-validation",
        action="store_true",
        help="不运行validate_deliverables验证 / Skip validate_deliverables check"
    )

    args = parser.parse_args()

    status_info = check_experiment_status(
        args.run_dir,
        require_validation=not args.no_validation
    )

    # Print result
    print(f"\n[Experiment Status Check]")
    print(f"  Directory: {args.run_dir}")
    print(f"  Status: {status_info['status_emoji']} {status_info['status_str']}")
    print(f"  Details: {status_info['details']}")

    if status_info["missing_files"]:
        print(f"\n  Missing files ({len(status_info['missing_files'])}):")
        for f in status_info["missing_files"]:
            print(f"    - {f}")

    if status_info["validation_error"]:
        print(f"\n  Validation error:")
        print(f"    {status_info['validation_error'][:200]}")

    # Exit code
    if status_info["status"] == ExperimentStatus.COMPLETED:
        sys.exit(0)
    elif status_info["status"] == ExperimentStatus.FAILED:
        sys.exit(1)
    else:
        sys.exit(2)  # Running or not started


if __name__ == "__main__":
    main()
